def request_prefill(service_slug):
    """Return only server-authored initial values; never trust arbitrary query copy."""
    key = str(service_slug or "").strip()
    guide = SERVICE_GUIDES.get(key) or STATIC_SERVICE_LANDINGS.get(key)
    if not guide:
        return {}
    return {"request_type": guide["request_type"], "title": guide["request_title"]}


def service_page_context(page):
    guide = SERVICE_GUIDES.get(str(page.slug or ""))
    if not guide:
        return {"service_guide": None, "service_seo_title": "", "service_seo_description": ""}
    default_title = f"{page.title} | 3DprintHub"
    use_editorial_title = not str(page.meta_title or "").strip() or str(page.meta_title).strip() == default_title
    use_editorial_description = (
        not str(page.meta_description or "").strip()
        or str(page.meta_description).strip() == str(page.short_description or "").strip()
    )
    return {
        "service_guide": guide,
        "service_seo_title": guide["meta_title"] if use_editorial_title else page.meta_title,
        "service_seo_description": guide["meta_description"] if use_editorial_description else page.meta_description,
    }


def service_landing_view(request, slug):
    profile = STATIC_SERVICE_LANDINGS.get(str(slug or ""))
    if profile is None:
        raise Http404("صفحه خدمت پیدا نشد.")
    return render(
        request,
        "store/service_landing.html",
        {"service": profile, "service_slug": slug},
    )
